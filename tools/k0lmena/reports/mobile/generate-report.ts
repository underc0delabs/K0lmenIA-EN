// reports/mobile/generate-report.ts — HTML report of the mobile suite (npm run report:mobile),
// with the k0lmenIA dark theme.

import { hostname } from 'os';
import { resolve } from 'path';

// eslint-disable-next-line @typescript-eslint/no-var-requires
const { reportOptions, applyTheme, waitForHtml } = require('../dark-theme');

// multiple-cucumber-html-reporter v4 is ESM only: it is loaded with a dynamic import()
// (with new Function so TypeScript does not turn it into require).
const loadReporter = new Function('m', 'return import(m)') as (m: string) => Promise<any>;

const output = resolve(__dirname, 'html');

loadReporter('multiple-cucumber-html-reporter')
  .then(({ generate }) => generate({
    ...reportOptions('Mobile'),
    // Directory where the JSON generated by Cucumber is
    jsonDir: resolve(__dirname),
    // Directory where the HTML will be generated
    reportPath: output,
    metadata: {
      browser: { name: 'Appium', version: '-' },
      device: process.env.MOBILE_DEVICE_NAME || hostname(),
      platform: {
        name: process.env.MOBILE_PLATFORM || 'Android',
        version: process.env.MOBILE_PLATFORM_VERSION || '-',
      },
    },
    customData: {
      Project: 'k0lmena · Mobile',
      'Run at': new Date().toLocaleString('en-US'),
      Target: process.env.MOBILE_TARGET || '—',
    },
  }))
  .then(() => waitForHtml(output))
  .then((ready: boolean) => { if (!ready) console.error('[k0lmena] Note: the reporter did not finish writing index.html in time.'); })
  .then(() => console.log(`[k0lmena] Mobile report with dark theme (${applyTheme(output)} pages).`))
  .catch((e: unknown) => {
    console.error('[k0lmena] Could not generate the mobile report:', e);

    process.exitCode = 1;
  });
